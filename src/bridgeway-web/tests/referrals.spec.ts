import { test, expect } from "@playwright/test";

test("fictional Cosmos referral flow, card controls, and responsive templates", async ({ page }) => {
  await page.goto("/r/demo-west-office");
  await expect(page.getByText("West Office Demo", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Let’s get acquainted." })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const name = "Fictional Browser Demo " + Date.now();
  await page.getByLabel("Patient name").fill(name);
  await page.getByLabel("Email address").fill("fictional@example.invalid");
  await page.getByLabel("Phone number").fill("8015550100");
  await page.getByLabel("Anything you’d like us to know?").fill("Fictional verification record. No real patient information.");
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Request my consultation" }).click();
  await expect(page.getByRole("heading", { name: "We look forward to meeting you." })).toBeVisible();
  await page.goto("/staff");
  const patient = page.getByRole("article").filter({ has: page.getByRole("heading", { name, exact: true }) });
  await expect(patient).toBeVisible();
  await patient.getByRole("combobox").selectOption("Scheduled");
  await expect(patient.getByRole("combobox")).toHaveValue("Scheduled");
  await page.getByRole("button", { name: /^Scheduled\s*\d/ }).click();
  await expect(patient).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Monthly trend", exact: true }).click();
  await expect(page.getByRole("img", { name: /12-month/ })).toBeVisible();
  await page.getByLabel("Measure", { exact: true }).selectOption("opens");
  await expect(page.getByRole("img", { name: /link opens/ })).toBeVisible();
  await page.getByLabel("Referring office name").fill("Fictional Office " + Date.now());
  await page.getByRole("button", { name: "Create referral link" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Referral link created." })).toBeVisible();
  const doctor = page.locator(".doctor-row").last();
  const href = await doctor.locator("a").getAttribute("href");
  await doctor.getByRole("button", { name: "Deactivate", exact: true }).click();
  await expect(doctor.getByText("Inactive", { exact: true })).toBeVisible();
  await page.goto(href!);
  await expect(page.getByRole("heading", { name: "This link is unavailable." })).toBeVisible();
  await page.goto("/staff");
  const inactive = page.locator(".doctor-row").filter({ has: page.locator(`a[href="${href}"]`) });
  await inactive.getByRole("button", { name: "Reactivate" }).click();
  await expect(inactive.getByText("Active", { exact: true })).toBeVisible();
  await page.goto(href!);
  await expect(page.getByRole("heading", { name: "Let’s get acquainted." })).toBeVisible();
  await page.goto("/staff");
  await expect(page.locator(".referral").first()).toBeVisible();
  await page.route("**/api/staff/session", route => route.fulfill({ status: 401, contentType: "application/json", body: '{"error":"Please sign in."}' }));
  await page.getByRole("button", { name: "Refresh inbox" }).click();
  await expect(page.getByRole("heading", { name: "Please sign in again" })).toBeVisible();
  await expect(page.locator(".referral")).toHaveCount(0);
});

test("API preserves idempotency, validation and optimistic concurrency", async ({ request }) => {
  const headers = { Origin: "http://localhost:3000" };
  const submissionId = crypto.randomUUID();
  const data = { name: "Fictional API Demo", email: "fictional@example.invalid", phone: "8015550101", notes: "Fictional only", consent: true, code: "demo-west-office", submissionId };
  expect((await request.post("/api/referrals", { headers, data })).status()).toBe(201);
  expect((await request.post("/api/referrals", { headers, data })).status()).toBe(201);
  const inbox = await (await request.get("/api/staff/referrals")).json();
  const rows = inbox.referrals.filter((r: { id: string }) => r.id === "ref-" + submissionId);
  expect(rows).toHaveLength(1);
  const patch = { status: "Contacted", etag: rows[0].etag };
  expect((await request.patch("/api/staff/referrals/" + rows[0].id, { headers, data: patch })).status()).toBe(200);
  expect((await request.patch("/api/staff/referrals/" + rows[0].id, { headers, data: patch })).status()).toBe(409);
  expect((await request.post("/api/referrals", { headers, data: { ...data, consent: false } })).status()).toBe(400);
  expect((await request.post("/api/referrals", { headers: { Origin: "https://untrusted.invalid" }, data })).status()).toBe(403);
  expect((await request.get("/api/staff/analytics?month=not-a-month")).status()).toBe(400);
  const event = { code: "demo-west-office", eventId: crypto.randomUUID() };
  const before = await (await request.get("/api/staff/analytics")).json();
  await request.post("/api/link-opens", { headers, data: event });
  await request.post("/api/link-opens", { headers, data: event });
  const after = await (await request.get("/api/staff/analytics")).json();
  expect(after.linkOpens).toBe(before.linkOpens + 1);
  const analytics = await (await request.get("/api/staff/analytics")).text();
  expect(analytics).not.toContain("fictional@example.invalid");
  expect((await request.get("/health/cosmos")).ok()).toBe(true);
});
